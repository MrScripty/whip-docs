#!/usr/bin/env python3
"""Verify the exact committed grammar inputs Cargo will compile; no network/build.

Run a locked host build first in a fresh checkout. CARGO/CARGO_HOME/RUSTC overrides
are honored. Metadata is limited to the host, so unrelated cross-target packages
need not be cached. This verifies committed sources, not fresh regeneration.
"""

import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys


def main():
    root = Path(__file__).resolve().parent.parent
    pins = json.loads((root / "docs/design/grammar-pins.json").read_text())
    rustc = subprocess.check_output(
        [os.environ.get("RUSTC", "rustc"), "-vV"], text=True,
    )
    host = next(line.removeprefix("host: ") for line in rustc.splitlines() if line.startswith("host: "))
    metadata = json.loads(subprocess.check_output(
        [os.environ.get("CARGO", "cargo"), "metadata", "--format-version", "1",
         "--locked", "--offline", "--no-default-features", "--filter-platform", host], cwd=root, text=True,
    ))
    verified = 0
    for pin in pins["packages"]:
        generated = pin.get("generatedParser")
        if generated is None:
            continue
        package = next(p for p in metadata["packages"]
                       if p["name"] == pin["package"] and p["source"] == pin["source"])
        base = Path(package["manifest_path"]).parent
        commit = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=base, text=True,
        ).strip()
        if commit != pin["upstreamCommit"]:
            raise ValueError(f"unexpected checkout revision for {pin['package']}")
        for relative, expected in generated["files"].items():
            path = (base / relative).resolve()
            if not path.is_relative_to(base.resolve()):
                raise ValueError(f"invalid input path: {relative}")
            actual = hashlib.sha256(path.read_bytes()).hexdigest()
            if actual != expected:
                raise ValueError(f"hash mismatch: {pin['package']}/{relative}")
        parser = (base / "src/parser.c").read_text()
        abi = int(re.search(r"#define LANGUAGE_VERSION (\d+)", parser)[1])
        if abi != generated["abi"] or parser.splitlines()[0] != generated["generatorDeclaration"]:
            raise ValueError(f"generated parser metadata mismatch: {pin['package']}")
        verified += 1
        print(f"{pin['package']} {commit}: ABI {abi}, {len(generated['files'])} input hashes verified")
    if verified != 2:
        raise ValueError(f"expected two official Git grammars, verified {verified}")
    print("Committed-source provenance verified; parsers were not regenerated by this check.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, StopIteration, subprocess.CalledProcessError) as error:
        print(f"Grammar provenance verification failed: {error}", file=sys.stderr)
        sys.exit(1)
